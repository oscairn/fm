/// Routing `n` (1-88; others give routing 1).
pub fn routing(n: i16) -> Routing {
    let i = usize::try_from(n.saturating_sub(1)).unwrap_or(0);
    ROUTINGS.get(i).copied().unwrap_or(r([0; OPS], 0xff, 0, 0))
}

