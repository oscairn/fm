    fn parse(s: &str) -> Routing {
        let mut g = Routing {
            mods: [0; OPS],
            carriers: 0,
            fb_from: 0,
            fb_to: 0,
        };
        let n = |x: &str| x.trim().parse::<usize>().unwrap() - 1;
        for part in s.split(" | ") {
            if let Some(c) = part.strip_prefix("out: ") {
                g.carriers = c.split(',').fold(0, |m, x| m | 1 << n(x));
            } else if let Some(f) = part.strip_prefix("fb: ") {
                let (a, b) = f.split_once("->").unwrap();
                (g.fb_from, g.fb_to) = (n(a) as u8, n(b) as u8);
            } else {
                for edge in part.split("; ") {
                    let (m, targets) = edge.split_once('>').unwrap();
                    for t in targets.split(',') {
                        g.mods[n(t)] |= 1 << n(m);
                    }
                }
            }
        }
        g
    }

    #[test]
    fn routings_match_the_chart() {
        for (i, (got, chart)) in ROUTINGS.iter().zip(CHART).enumerate() {
            let mut want = parse(chart);
            if i + 1 == 70 {
                // the chart reads 1 > 2 > 3; the reference's output shows 1 and 2 both modulating 3
                want.mods[1] = 0;
                want.mods[2] = 0b11;
            }
            assert_eq!(*got, want, "routing {}", i + 1);
        }
    }

    #[test]
    fn every_routing_is_well_formed() {
        for (i, g) in ROUTINGS.iter().enumerate() {
            for (k, &m) in g.mods.iter().enumerate() {
                assert_eq!(
                    u32::from(m) >> k,
                    0,
                    "routing {}: operator {} modulated from above",
                    i + 1,
                    k + 1
                );
            }
            // each operator is a carrier or modulates something, never both
            for k in 0..OPS {
                let modulates = g.mods.iter().any(|&m| m >> k & 1 != 0);
                assert!(
                    modulates != (g.carriers >> k & 1 != 0),
                    "routing {} operator {}",
                    i + 1,
                    k + 1
                );
            }
            assert!(g.fb_from >= g.fb_to);
            let loops = g.fb_from > g.fb_to;
            assert_eq!(loops, i + 1 == 12 || i + 1 == 14, "routing {}", i + 1);
        }
        assert_eq!(routing(12).fb_from, 4);
        assert_eq!(routing(0), ROUTINGS[0]);
    }
