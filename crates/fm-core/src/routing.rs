//! The model's 88 routings (algorithms) as data: which operator modulates which, the carriers,
//! the feedback path, and the carriers' output level per routing (in `laws`).

use crate::params::OPS;

/// Operators are numbered from 0; `mods[i]` has bit `j` set when operator `j` modulates operator
/// `i` (always `j < i`). Feedback runs from `fb_from`'s output into `fb_to`'s input, one sample
/// late: the same operator, or (routings 12 and 14) a loop through the operators between.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Routing {
    pub mods: [u8; OPS],
    pub carriers: u8,
    pub fb_from: u8,
    pub fb_to: u8,
}

const fn r(mods: [u8; OPS], carriers: u8, fb_from: u8, fb_to: u8) -> Routing {
    Routing {
        mods,
        carriers,
        fb_from,
        fb_to,
    }
}

